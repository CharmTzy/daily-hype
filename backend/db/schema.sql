CREATE OR REPLACE VIEW product_details_view AS
WITH image_agg AS (
  SELECT
    pi.productid,
    ARRAY_AGG(i.url ORDER BY i.imageid) AS urls
  FROM productimage pi
  JOIN image i ON i.imageid = pi.imageid
  GROUP BY pi.productid
)
SELECT
  p.productid,
  p.productname,
  p.unitprice,
  p.description,
  p.soldqty,
  p.rating,
  COALESCE(image_agg.urls, ARRAY[]::TEXT[]) AS urls,
  p.typeid,
  t.typename AS type,
  c.categoryname AS category,
  p.categoryid,
  co.colourname AS colour,
  pd.colourid,
  co.hex,
  s.sizename AS size,
  pd.sizeid,
  pd.qty,
  pd.productstatus,
  pd.productdetailid,
  p.createdat,
  p.updatedat
FROM product p
JOIN productdetail pd ON pd.productid = p.productid
JOIN type t ON t.typeid = p.typeid
JOIN category c ON c.categoryid = p.categoryid
JOIN colour co ON co.colourid = pd.colourid
JOIN size s ON s.sizeid = pd.sizeid
LEFT JOIN image_agg ON image_agg.productid = p.productid;

CREATE OR REPLACE VIEW search_product AS
WITH detail_agg AS (
  SELECT
    pd.productid,
    ARRAY_AGG(co.colourname ORDER BY co.colourname, s.sizename) AS colour,
    ARRAY_AGG(co.hex ORDER BY co.colourname, s.sizename) AS hex,
    ARRAY_AGG(s.sizename ORDER BY co.colourname, s.sizename) AS size,
    COALESCE(SUM(pd.qty), 0) AS qty
  FROM productdetail pd
  JOIN colour co ON co.colourid = pd.colourid
  JOIN size s ON s.sizeid = pd.sizeid
  GROUP BY pd.productid
),
image_agg AS (
  SELECT
    pi.productid,
    COALESCE(ARRAY_AGG(DISTINCT i.url) FILTER (WHERE i.url IS NOT NULL), ARRAY[]::TEXT[]) AS urls
  FROM productimage pi
  JOIN image i ON i.imageid = pi.imageid
  GROUP BY pi.productid
)
SELECT
  p.productid,
  p.productname,
  p.description,
  p.unitprice,
  p.rating,
  p.soldqty,
  p.createdat,
  p.updatedat,
  t.typename AS type,
  c.categoryname AS category,
  COALESCE(detail_agg.colour, ARRAY[]::TEXT[]) AS colour,
  COALESCE(detail_agg.hex, ARRAY[]::TEXT[]) AS hex,
  COALESCE(detail_agg.size, ARRAY[]::TEXT[]) AS size,
  COALESCE(image_agg.urls, ARRAY[]::TEXT[]) AS urls,
  COALESCE(detail_agg.qty, 0) AS qty,
  CASE
    WHEN COALESCE(detail_agg.qty, 0) > 0 THEN 'in stock'
    ELSE 'out of stock'
  END AS productstatus
FROM product p
JOIN type t ON t.typeid = p.typeid
JOIN category c ON c.categoryid = p.categoryid
JOIN detail_agg ON detail_agg.productid = p.productid
LEFT JOIN image_agg ON image_agg.productid = p.productid;
