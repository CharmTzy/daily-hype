  updatedat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS productdetail (
  productdetailid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  productid INTEGER NOT NULL REFERENCES product(productid) ON DELETE CASCADE,
  colourid INTEGER NOT NULL REFERENCES colour(colourid) ON DELETE RESTRICT,
